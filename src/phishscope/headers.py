import re

from .domains import (
    FREEMAIL,
    brand_in_text,
    domain_of,
    impersonated_brand,
    is_official,
    is_public_ip,
    same_org,
)
from .scoring import Finding

EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
IP_RE = re.compile(r"\[(?:IPv6:)?([0-9a-fA-F:.]+)\]")
FROM_RE = re.compile(r"\bfrom\s+(\S+)", re.I)
BY_RE = re.compile(r"\bby\s+(\S+)", re.I)


def received_hops(received):
    hops = []
    for header in reversed(received):
        ips = IP_RE.findall(header)
        from_match, by_match = FROM_RE.search(header), BY_RE.search(header)
        hops.append({
            "from": from_match.group(1) if from_match else "",
            "by": by_match.group(1) if by_match else "",
            "ip": ips[0] if ips else "",
            "date": header.rsplit(";", 1)[1].strip() if ";" in header else "",
        })
    return hops


def originating_ip(received):
    for header in reversed(received):
        for ip in IP_RE.findall(header):
            if is_public_ip(ip):
                return ip
    return ""


def check_headers(parsed):
    findings = []
    sender = parsed.from_addr
    domain = parsed.from_domain

    if not sender or not domain:
        findings.append(Finding("headers", "Missing or malformed From address", 15))
        return findings

    for addr in parsed.reply_to:
        if not same_org(domain_of(addr), domain):
            findings.append(Finding("headers", f"Reply-To ({addr}) sends replies to a different domain than From ({sender})", 15))

    if parsed.return_path and "@" in parsed.return_path and not same_org(domain_of(parsed.return_path), domain):
        findings.append(Finding("headers", f"Return-Path ({parsed.return_path}) does not match the From domain", 5))

    embedded = EMAIL_RE.search(parsed.from_name)
    if embedded and not same_org(domain_of(embedded.group()), domain):
        findings.append(Finding("headers", f"Display name shows {embedded.group()} but the real sender is {sender}", 20))

    brand = brand_in_text(parsed.from_name)
    if brand and not is_official(domain, brand):
        extra = " (a free webmail account)" if domain in FREEMAIL else ""
        findings.append(Finding("headers", f"Display name claims to be {brand.title()} but mail comes from {domain}{extra}", 20))

    lookalike = impersonated_brand(domain)
    if lookalike:
        findings.append(Finding("headers", f"Sender domain {domain} imitates {lookalike.title()}", 25))

    if not parsed.message_id:
        findings.append(Finding("headers", "Message-ID header is missing", 5))
    else:
        mid = re.search(r"@([^>\s]+)", parsed.message_id)
        if mid and not same_org(mid.group(1), domain):
            findings.append(Finding("headers", f"Message-ID was generated by {mid.group(1)}, not {domain}", 3))

    if not parsed.date:
        findings.append(Finding("headers", "Date header is missing", 3))

    return findings
